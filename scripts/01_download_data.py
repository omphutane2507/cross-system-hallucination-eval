"""
Step 1: Download FaithBench dataset.

FaithBench is released as JSON batch files on GitHub (not on the HF Hub),
so we clone/download directly from the repo:
https://github.com/vectara/FaithBench

Each batch file (batch_1.json ... batch_16.json, skipping batch_13) contains
samples with a source document, a summary generated by a modern LLM, and
human annotations marking which spans (if any) are hallucinated.

Run this once. It downloads all batches into ./data/raw/
"""

import os
import json
import urllib.request

RAW_DIR = os.path.join(os.path.dirname(__file__), "..", "data", "raw")
os.makedirs(RAW_DIR, exist_ok=True)

BASE_URL = "https://raw.githubusercontent.com/vectara/FaithBench/main/data_for_release/batch_{}.json"

# Batches go from 1 to 16, but batch 13 does not exist in the release
BATCH_IDS = [i for i in range(1, 17) if i != 13]


def download_batch(batch_id: int) -> bool:
    url = BASE_URL.format(batch_id)
    dest = os.path.join(RAW_DIR, f"batch_{batch_id}.json")
    if os.path.exists(dest):
        print(f"  batch_{batch_id}.json already present, skipping")
        return True
    try:
        urllib.request.urlretrieve(url, dest)
        print(f"  downloaded batch_{batch_id}.json")
        return True
    except Exception as e:
        print(f"  FAILED batch_{batch_id}: {e}")
        return False


def main():
    print(f"Downloading FaithBench batches into {RAW_DIR} ...")
    ok = 0
    for bid in BATCH_IDS:
        if download_batch(bid):
            ok += 1
    print(f"\nDone. {ok}/{len(BATCH_IDS)} batches downloaded successfully.")
    print("If any failed, check your internet connection or download manually")
    print("from https://github.com/vectara/FaithBench/tree/main/data_for_release")


if __name__ == "__main__":
    main()
